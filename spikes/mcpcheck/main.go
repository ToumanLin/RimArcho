// Command mcpcheck is the I4 self-check: a scripted MCP client that drives `archo mcp`
// against the real environment like an agent without skills would, and writes the
// transcript as Markdown. It only calls tools annotated readOnlyHint (it refuses anything
// else), so the game, the workshop, Mods/ and ModsConfig.xml are never written.
//
//	go run ./spikes/mcpcheck -archo bin/archo.exe -out docs/m4-mcp-transcripts.md
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"regexp"
	"strings"
	"time"

	sdk "github.com/modelcontextprotocol/go-sdk/mcp"
)

type session struct {
	cs       *sdk.ClientSession
	readOnly map[string]bool
	md       strings.Builder
	calls    int
}

func (s *session) note(format string, a ...any) { fmt.Fprintf(&s.md, format+"\n\n", a...) }

func (s *session) call(name string, args map[string]any) string {
	if !s.readOnly[name] {
		log.Fatalf("refusing %s: not annotated readOnlyHint", name)
	}
	s.calls++
	t0 := time.Now()
	res, err := s.cs.CallTool(context.Background(), &sdk.CallToolParams{Name: name, Arguments: args})
	if err != nil {
		log.Fatalf("%s: %v", name, err)
	}
	var out strings.Builder
	for _, c := range res.Content {
		out.WriteString(c.(*sdk.TextContent).Text)
	}
	shown := map[string]any{}
	for k, v := range args {
		if str, ok := v.(string); ok && len(str) > 200 {
			v = fmt.Sprintf("<%d characters, shown above>", len(str))
		}
		shown[k] = v
	}
	j, _ := json.Marshal(shown)
	fmt.Fprintf(&s.md, "**→ `%s` `%s`** (%.1f s%s)\n\n```\n%s```\n\n", name, j, time.Since(t0).Seconds(),
		map[bool]string{true: ", isError", false: ""}[res.IsError], out.String())
	return out.String()
}

var (
	clusterRe = regexp.MustCompile(`(?m)^\s+log:(E\d+) (\S+) x(\d+)  (.*?)(?:  → (#\w+) \((\w+)[^)]*\))??$`)
	modRefRe  = regexp.MustCompile(`#[0-9a-z]{4}`)
	patchRe   = regexp.MustCompile(`(?m)^\s+(#[0-9a-z]{4}) (.+?)  ([\w.+]+)\.(\w+)(  \(.*\))?$`)
	pkgRe     = regexp.MustCompile(`(?m)^\s+package: (\S+)`)
	failedRe  = regexp.MustCompile(`patches --mod (#\w+) --failed`)
)

func main() {
	exe := flag.String("archo", `bin\archo.exe`, "archo executable")
	out := flag.String("out", `docs\m4-mcp-transcripts.md`, "transcript file")
	flag.Parse()
	ctx := context.Background()
	c := sdk.NewClient(&sdk.Implementation{Name: "mcpcheck", Version: "0"}, nil)
	cs, err := c.Connect(ctx, &sdk.CommandTransport{Command: exec.Command(*exe, "mcp")}, nil)
	if err != nil {
		log.Fatal(err)
	}
	defer cs.Close()
	s := &session{cs: cs, readOnly: map[string]bool{}}
	tools, err := cs.ListTools(ctx, nil)
	if err != nil {
		log.Fatal(err)
	}
	var names []string
	for _, t := range tools.Tools {
		if t.Annotations != nil && t.Annotations.ReadOnlyHint {
			s.readOnly[t.Name] = true
			names = append(names, t.Name)
		}
	}
	start := time.Now()
	s.note("# M4 MCP self-check (I4)\n\nGenerated by `go run ./spikes/mcpcheck` on %s against the real environment. The client connects to `archo mcp` over stdio, loads no skill, and only calls tools annotated `readOnlyHint` (%s). Each step's choice of the next call is made from the previous output alone, the way an agent reading the tool descriptions would.",
		start.Format("2006-01-02 15:04"), strings.Join(names, ", "))
	s.note("Server instructions (first line): %q", strings.SplitN(cs.InitializeResult().Instructions, "\n", 2)[0])

	// ---- Diagnosis 1: a patch failure ----
	s.note("## 1. Patch failure\n\nUser: \"My log is full of `Patch operation … failed` lines. Which mod is wrong and how do I fix it?\"")
	s.call("status", nil)
	summary := s.call("analyze_log", nil)
	var pf, tick []string
	for _, m := range clusterRe.FindAllStringSubmatch(summary, -1) {
		// Prefer a failure with a second candidate (a dependency): the richer diagnosis.
		if m[2] == "patch-failed" && (pf == nil || (!strings.Contains(pf[0], ", +") && strings.Contains(m[0], ", +"))) {
			pf = m
		}
		if (m[2] == "harmony-stack" || m[2] == "exception") && strings.Contains(m[4], "Tick") && tick == nil {
			tick = m
		}
	}
	if pf == nil {
		s.note("The current log has no patch-failed cluster; trying Player-prev.log.")
		summary = s.call("analyze_log", map[string]any{"prev": true})
		for _, m := range clusterRe.FindAllStringSubmatch(summary, -1) {
			if m[2] == "patch-failed" && pf == nil {
				pf = m
			}
		}
	}
	if pf != nil {
		s.note("The summary lists cluster `log:%s` as a patch failure (x%s); its detail gives the file, the simulation's reason and the candidate roles.", pf[1], pf[3])
		doc := s.call("analyze_log", map[string]any{"cluster": pf[1]})
		if m := failedRe.FindStringSubmatch(doc); m != nil {
			s.call("get_mod", map[string]any{"ref": m[1]})
			s.call("get_patches", map[string]any{"mod": m[1], "failed": true})
		}
		for _, l := range strings.Split(doc, "\n") {
			if strings.Contains(l, "  dependency  ") {
				s.note("A second candidate has the role dependency: look at its state.")
				s.call("get_mod", map[string]any{"ref": modRefRe.FindString(l)})
				break
			}
		}
	} else {
		s.note("No patch failure in either log; diagnosis 1 skipped.")
	}

	// ---- Diagnosis 2: a Pawn.Tick-style stack ----
	s.note("## 2. Pawn.Tick-style exception\n\nUser pastes: \"Exception ticking … ArgumentOutOfRangeException … at Verse.Pawn.Tick\" with Harmony patch lines.")
	h := s.call("get_harmony", map[string]any{"target": "Verse.Pawn.Tick"})
	// Build the pasted stack from the real patches on Pawn.Tick (up to three mods), the way
	// the game prints them: the patched frame, then one line per patch.
	type pt struct{ ref, kind, typ, method string }
	var pts []pt
	kind := ""
	for _, l := range strings.Split(h, "\n") {
		switch strings.TrimSpace(l) {
		case "prefixes:":
			kind = "PREFIX"
		case "postfixes:":
			kind = "POSTFIX"
		case "transpilers:":
			kind = "TRANSPILER"
		case "finalizers:":
			kind = "FINALIZER"
		}
		if m := patchRe.FindStringSubmatch(l); m != nil && kind != "" && len(pts) < 3 {
			pts = append(pts, pt{m[1], kind, m[3], m[4]})
		}
	}
	var stack strings.Builder
	stack.WriteString("Exception ticking Human123 (at (120, 0, 80)): System.ArgumentOutOfRangeException: Index was out of range. Must be non-negative and less than the size of the collection.\n")
	stack.WriteString("Parameter name: index\n[Ref 7F3A21C0]\n")
	stack.WriteString("  at System.ThrowHelper.ThrowArgumentOutOfRangeException (System.ExceptionArgument argument, System.ExceptionResource resource) [0x00029] in <00000000000000000000000000000000>:0\n")
	stack.WriteString("  at System.Collections.Generic.List`1[T].get_Item (System.Int32 index) [0x00009] in <00000000000000000000000000000000>:0\n")
	stack.WriteString("  at Verse.ThingWithComps.Tick () [0x0001a] in <00000000000000000000000000000000>:0\n")
	stack.WriteString("  at (wrapper dynamic-method) Verse.Pawn.Verse.Pawn.Tick_Patch1(Verse.Pawn)\n")
	pkgs := map[string]string{}
	for _, p := range pts {
		if _, ok := pkgs[p.ref]; !ok {
			if m := pkgRe.FindStringSubmatch(s.call("get_mod", map[string]any{"ref": p.ref})); m != nil {
				pkgs[p.ref] = m[1]
			}
		}
		ret := "Void"
		if p.kind == "PREFIX" {
			ret = "Boolean"
		}
		fmt.Fprintf(&stack, "    - %s %s: %s %s:%s(Verse.Pawn __instance)\n", p.kind, pkgs[p.ref], ret, p.typ, p.method)
	}
	stack.WriteString("  at Verse.TickList.Tick () [0x0015c] in <00000000000000000000000000000000>:0\n")
	stack.WriteString("  at Verse.TickManager.DoSingleTick () [0x00090] in <00000000000000000000000000000000>:0\n")
	s.note("The pasted text (built from the real patches on `Verse.Pawn.Tick` found above, in the game's format):\n\n```\n%s```", stack.String())
	sum := s.call("analyze_log", map[string]any{"text": stack.String()})
	id := "E1"
	if m := clusterRe.FindStringSubmatch(sum); m != nil {
		id = m[1]
	}
	doc := s.call("analyze_log", map[string]any{"text": stack.String(), "cluster": id})
	if len(pts) > 0 {
		s.note("The attribution marks these mods as patchers, not the source; the checklist points at AllComps mutations. Read one patch class, then search the decompiled code of the patchers.")
		s.call("read_source", map[string]any{"ref": pts[0].ref, "type": pts[0].typ})
		var in []string
		seen := map[string]bool{}
		for _, p := range pts {
			if !seen[p.ref] {
				seen[p.ref] = true
				in = append(in, p.ref)
			}
		}
		s.call("read_source", map[string]any{"search": "AllComps.Remove(", "in": in, "budget": 60})
	}
	_ = doc
	if tick != nil {
		s.note("The real log also has a tick cluster, `log:%s`:", tick[1])
		s.call("analyze_log", map[string]any{"cluster": tick[1]})
	}
	s.note("---\n\n%d tool calls, %.1f s in all.", s.calls, time.Since(start).Seconds())
	if err := os.WriteFile(*out, []byte(s.md.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d calls, %.1f s → %s\n", s.calls, time.Since(start).Seconds(), *out)
}
