// The generated Mod RimArcho Looks Preference (21 §4): About/About.xml and, for every slot whose choice
// is applied, the chosen file under its key's path. It is built beside itself and swapped
// in, never edited in place, and never written through a link into a Mod.

// looksVersions are the game versions the generated Mod declares, as Archo Monitor's About.xml.
var looksVersions = []string{"1.5", "1.6", "1.7"}

const looksOldSuffix = ".archo-old"

// LooksFile is one file of the generated Mod.
type LooksFile struct {
	Rel    string // relative to the generated Mod's folder, forward slashes
	Source string // the Mod's file
	Size   int64
	MTime  int64  // the source's, unix nanoseconds
	Linked bool   // a hard link (in a dry run: expected to be one); false: a copy
	Look   string // the look and slot it is written for
	Slot   string
}

// LooksBuild is one rebuild of the generated Mod, or with DryRun what it would write.
type LooksBuild struct {
	Dir       string // the generated Mod's folder
	Files     []LooksFile
	DryRun    bool
	Unchanged bool // the result equals what is on disk: nothing was written
	Links     int
	Copies    int
}

func looksAbout() string {
	var sb strings.Builder
	sb.WriteString("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<ModMetaData>\n")
	fmt.Fprintf(&sb, "  <packageId>%s</packageId>\n  <name>%s</name>\n  <author>RimArcho</author>\n", LooksPackage, LooksName)
	sb.WriteString("  <description>Generated by RimArcho (looks): the textures chosen for the plan last written to the game. RimArcho rebuilds this folder; do not edit it.</description>\n")
	sb.WriteString("  <supportedVersions>\n")
	for _, v := range looksVersions {
		fmt.Fprintf(&sb, "    <li>%s</li>\n", v)
	}
	sb.WriteString("  </supportedVersions>\n</ModMetaData>\n")
	return sb.String()
}

// looksSkeleton creates the generated Mod's folder with its About.xml when it has none. It
// touches nothing that exists, so it is allowed while a game runs.
func looksSkeleton(dir string) error {
	about := filepath.Join(dir, "About", "About.xml")
	if _, err := os.Lstat(about); err == nil {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(about), 0o755); err != nil {
		return err
	}
	return writeNew(about, []byte(looksAbout()))
}

// writeNew writes a file that must not exist yet: it never opens an existing path.
func writeNew(path string, data []byte) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

// looksPlan lists the files the generated Mod holds for ls: for every slot whose choice is
// applied, the chosen file, its second format and its mask (21 §4 "Contents").
func looksPlan(ls *LooksState) []LooksFile {
	ids := make([]string, 0, len(ls.Looks))
	for id := range ls.Looks {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var out []LooksFile
	seen := map[string]bool{}
	add := func(f *looks.File, look, slot string) {
		for ; f != nil; f = f.Alt {
			rel := "Textures/" + f.Tex
			if f.Tex == "" || seen[strings.ToLower(rel)] {
				continue
			}
			seen[strings.ToLower(rel)] = true
			out = append(out, LooksFile{Rel: rel, Source: f.Path, Size: f.Size, MTime: f.MTime, Look: look, Slot: slot})
		}
	}
	for _, id := range ids {
		s := ls.Looks[id]
		if s.Look == nil {
			continue
		}
		wins := s.Look.InGame(s.Choice)
		for _, slot := range textureSlots(s.Look) {
			if s.Slots[slot] != LookApplied {
				continue
			}
			w := wins[slot]
			add(w.File, id, slot)
			if m := wins[looks.MaskOf(slot)]; m.File != nil && m.Pos == w.Pos {
				add(m.File, id, looks.MaskOf(slot))
			}
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Rel < out[j].Rel })
	return out
}

// looksCurrent reports whether the generated Mod in dir already holds exactly files: the
// recorded set (rel, source, size, mtime) equals it and every file is there.
func (a *App) looksCurrent(dir string, files []LooksFile) (bool, error) {
	rec, err := a.Store.LookFiles()
	if err != nil {
		return false, err
	}
	if _, err := os.Lstat(dir); err != nil {
		return len(files) == 0 && len(rec) == 0, nil // nothing was ever built and nothing is due
	}
	if _, err := os.Lstat(filepath.Join(dir, "About", "About.xml")); err != nil || len(rec) != len(files) {
		return false, nil
	}
	for i, f := range files { // both are ordered by Rel
		r := rec[i]
		if r.Rel != f.Rel || r.Source != f.Source || r.Size != f.Size || r.MTime != f.MTime {
			return false, nil
		}
		if _, err := os.Lstat(filepath.Join(dir, filepath.FromSlash(f.Rel))); err != nil {
			return false, nil
		}
	}
	for i := range files {
		files[i].Linked = rec[i].Linked
	}
	return true, nil
}

var errLooksRefused = errors.New("looks: rebuild refused")

// looksRebuild rebuilds the generated Mod in the looks directory dir from ls (21 §4
// "Rebuild"). A result equal to what is on disk writes nothing; otherwise it is refused
// while a game runs, built in a folder beside the Mod's and swapped in. dryRun writes
// nothing and still reports the refusal. h is the parent operation-log row, if any.
func (a *App) looksRebuild(ls *LooksState, dir string, dryRun bool, h *oplog.Handle) (*LooksBuild, error) {
	b := &LooksBuild{Dir: looksModDir(dir), DryRun: dryRun, Files: looksPlan(ls)}
	same, err := a.looksCurrent(b.Dir, b.Files)
	if err != nil {
		return b, err
	}
	if b.Unchanged = same; !same {
		a.looksExpectLinks(b)
		err = a.looksRefusal(dir)
		if err == nil && !dryRun {
			err = a.looksWrite(b)
		}
	}
	for _, f := range b.Files {
		if f.Linked {
			b.Links++
		} else {
			b.Copies++
		}
	}
	if !dryRun && !same {
		row := oplog.Row{Op: oplog.LooksBuild, EnvID: ls.St.Ix.Env.ID, Subject: ls.St.Plan.Name, Target: b.Dir,
			Result: opResult(err, errors.Is(err, errLooksRefused)), Detail: errText(err)}
		if err == nil {
			row.Detail = fmt.Sprintf("%s (%s, %s)", plural(len(b.Files), "file"), plural(b.Links, "hard link"), plural(b.Copies, "copy"))
		}
		a.opAdd(h, row)
	}
	return b, err
}

// looksRefusal says why the generated Mod cannot be replaced now: a game runs (09 §4), or
// the looks directory overlaps the data directory or a source root.
func (a *App) looksRefusal(dir string) error {
	if g, err := a.RunningGame(); err != nil {
		return err
	} else if g != nil {
		return fmt.Errorf("%w: %s is not rebuilt while a game runs (%s); the choices are kept and the next write to the game rebuilds it", errLooksRefused, LooksName, g.Describe(a.Loc))
	}
	if err := a.looksDirReady(dir); err != nil {
		return fmt.Errorf("%w: %v", errLooksRefused, err)
	}
	return nil
}

// looksExpectLinks marks the files a rebuild expects to hard-link: the source is on the
// Mod's volume and is not read-only (deleting a link to a read-only file clears the
// attribute, which the Mod's file shares).
func (a *App) looksExpectLinks(b *LooksBuild) {
	same := a.SameVolume
	if same == nil {
		same = source.SameVolume
	}
	for i := range b.Files {
		f := &b.Files[i]
		fi, err := os.Stat(f.Source)
		f.Linked = err == nil && fi.Mode().Perm()&0o200 != 0 && same(f.Source, b.Dir)
	}
}

// looksWrite builds b's files in a folder beside the generated Mod's and swaps it in, then
// records the files. Every destination is a new path in a new folder.
func (a *App) looksWrite(b *LooksBuild) error {
	tmp := b.Dir + TmpSuffix
	if err := os.RemoveAll(tmp); err != nil {
		return err
	}
	fail := func(err error) error {
		os.RemoveAll(tmp)
		return err
	}
	if err := looksSkeleton(tmp); err != nil {
		return fail(err)
	}
	link := a.HardLink
	if link == nil {
		link = os.Link
	}
	rec := make([]store.LookFile, 0, len(b.Files))
	for i := range b.Files {
		f := &b.Files[i]
		dst := filepath.Join(tmp, filepath.FromSlash(f.Rel))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return fail(err)
		}
		if !f.Linked || link(f.Source, dst) != nil {
			f.Linked = false
			if err := copyNew(f.Source, dst); err != nil {
				return fail(fmt.Errorf("copying %s: %w", f.Source, err))
			}
		}
		rec = append(rec, store.LookFile{Rel: f.Rel, Source: f.Source, Size: f.Size, MTime: f.MTime, Linked: f.Linked})
	}
	if err := swapDir(tmp, b.Dir); err != nil {
		return fail(err)
	}
	return a.Store.ReplaceLookFiles(rec)
}

// copyNew copies src to dst, which must not exist: it never opens an existing destination.
func copyNew(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

// swapDir puts the folder tmp in dir's place; the folder that was there is deleted (links
// and copies only: deleting a hard link leaves the Mod's file).
func swapDir(tmp, dir string) error {
	old := dir + looksOldSuffix
	if err := os.RemoveAll(old); err != nil {
		return err
	}
	if _, err := os.Lstat(dir); err != nil {
		return os.Rename(tmp, dir)
	}
	if err := os.Rename(dir, old); err != nil {
		return err
	}
	if err := os.Rename(tmp, dir); err != nil {
		os.Rename(old, dir)
		return err
	}
	os.RemoveAll(old)
	return nil
}

// looksForWrite rebuilds the generated Mod for the plan being written to the game (21 §4,
// 07 §4), so a Mod update that replaced a linked file is picked up. When the rebuild fails
// it returns the reason and marks the entry to be left out of this write.
func (a *App) looksForWrite(st *LoadoutState, dryRun bool) string {
	var entry *store.Mod
	for _, e := range st.List {
		if m := st.Ix.ByID[e.Instance]; IsLooks(m) && m.Status == identity.Live {
			entry = m
		}
	}
	if entry == nil {
		return ""
	}
	err := func() error {
		ls, err := a.LooksState(context.Background(), st, nil)
		if err != nil {
			return err
		}
		var h *oplog.Handle
		if st.op != nil {
			h = st.op.h
		}
		_, err = a.looksRebuild(ls, filepath.Dir(modDir(st.Ix, entry)), dryRun, h)
		return err
	}()
	if err == nil {
		return ""
	}
	st.leaveOut = map[string]bool{entry.ID: true}
	return strings.TrimPrefix(err.Error(), errLooksRefused.Error()+": ")
}
