// The Mods RimArcho generates in the looks directory (21 §4, §5): RimArcho Looks Preference
// (textures) and RimArcho Styles Preference (textures, Defs and patches). Both are built
// beside themselves and swapped in, never edited in place, and never written through a link
// into a Mod. This file holds what the two share: the folder, the Instance, the place at the
// end of the plan, the rebuild, and leaving one out of a write to the game.

// genMod describes one generated Mod.
type genMod struct {
	Package, Name, Link, folder string
	about                       string // the description in About.xml
	kept                        string // what a refused rebuild keeps: "choices" or "entries"
	addOp                       string // the plan edit that adds it, in the undo stack
	buildOp                     string // operation-log code of a rebuild
	// texts are the generated text files it may hold, relative to its folder.
	texts   []string
	files   func(*store.Store) ([]store.LookFile, error)
	replace func(*store.Store, []store.LookFile) error
}

var looksGen = &genMod{Package: LooksPackage, Name: LooksName, Link: LooksLink, folder: looksFolder,
	about: "Generated by RimArcho (looks): the textures chosen for the plan last written to the game. RimArcho rebuilds this folder; do not edit it.",
	kept:  "choices", addOp: LooksAddOp, buildOp: oplog.LooksBuild,
	files: (*store.Store).LookFiles, replace: (*store.Store).ReplaceLookFiles}

var stylesGen = &genMod{Package: StylesPackage, Name: StylesName, Link: StylesLink, folder: stylesFolder,
	about: "Generated by RimArcho (looks): styles and random variants that keep a Mod's version of a look, for the plan last written to the game. RimArcho rebuilds this folder; do not edit it.",
	kept:  "entries", addOp: StylesAddOp, buildOp: oplog.StylesBuild, texts: []string{stylesDefsRel, stylesPatchRel},
	files: (*store.Store).StyleFiles, replace: (*store.Store).ReplaceStyleFiles}

// generated lists the generated Mods in the order a plan holds them: both after every other
// Mod, RimArcho Looks Preference last so that its textures win (21 §4, §5; 08 §1.1).
var generated = []*genMod{stylesGen, looksGen}

// genVersions are the game versions a generated Mod declares, as Archo Monitor's About.xml.
var genVersions = []string{"1.5", "1.6", "1.7"}

const genOldSuffix = ".archo-old"

func genOf(m *store.Mod) *genMod {
	if m == nil || m.Kind != source.Extra {
		return nil
	}
	for _, g := range generated {
		if strings.EqualFold(m.PackageID, g.Package) {
			return g
		}
	}
	return nil
}

// IsGenerated reports whether m is a Mod RimArcho generates: RimArcho Looks Preference or
// RimArcho Styles Preference. Such a Mod is no part of the load order, supplies no look,
// and is never optimised or offered as a Mod of the player's.
func IsGenerated(m *store.Mod) bool { return genOf(m) != nil }

// ErrGenerated: the action is not offered for a Mod RimArcho generates.
var ErrGenerated = errors.New("generated by RimArcho")

// generatedRefusal refuses an action on a generated Mod's folder or identity (16 §2.9
// "Generated Mods"): RimArcho rebuilds the folder from the looks choices, so it is not
// deleted, locked, copied or regrouped like a Mod of the player's. doing completes "is not
// …" ("moved to the recycle bin"). nil when m is no generated Mod.
func generatedRefusal(ix *Index, m *store.Mod, doing string) error {
	g := genOf(m)
	if g == nil {
		return nil
	}
	return fmt.Errorf("%w: %s %s is rebuilt from the looks %s and is not %s; change what it holds in the plan editor's looks view or with archo looks, take it out of a plan with archo disable, and remove it for good with archo uninstall",
		ErrGenerated, ix.Ref(m.ID), g.Name, g.kept, doing)
}

// dir is the generated Mod's folder in the looks directory.
func (g *genMod) dir(looksDir string) string { return filepath.Join(looksDir, g.folder) }

// leftovers are the folder and what an interrupted rebuild leaves beside it.
func (g *genMod) leftovers() []string {
	return []string{g.folder, g.folder + TmpSuffix, g.folder + genOldSuffix}
}

func (g *genMod) aboutXML() string {
	var sb strings.Builder
	sb.WriteString("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<ModMetaData>\n")
	fmt.Fprintf(&sb, "  <packageId>%s</packageId>\n  <name>%s</name>\n  <author>RimArcho</author>\n", g.Package, g.Name)
	sb.WriteString("  <description>" + g.about + "</description>\n")
	sb.WriteString("  <supportedVersions>\n")
	for _, v := range genVersions {
		fmt.Fprintf(&sb, "    <li>%s</li>\n", v)
	}
	sb.WriteString("  </supportedVersions>\n</ModMetaData>\n")
	return sb.String()
}

// genStub is an empty language file every generated Mod carries. The game logs the error
// "Mod ... did not load any content" for a Mod that has no texture, Def, patch, assembly or
// file under Languages/ (Verse.ModContentPack.AnyContentLoaded), which is what a generated
// Mod is after its last choice is undone; the file adds no text to the game.
const (
	genStub     = "Languages/English/Keyed/RimArcho.xml"
	genStubData = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<LanguageData />\n"
)

// skeleton creates the generated Mod's folder with its About.xml and genStub where they
// are missing. It touches nothing that exists, so it is allowed while a game runs.
func (g *genMod) skeleton(dir string) error {
	for _, f := range [][2]string{{"About/About.xml", g.aboutXML()}, {genStub, genStubData}} {
		path := filepath.Join(dir, filepath.FromSlash(f[0]))
		if _, err := os.Lstat(path); err == nil {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := writeNew(path, []byte(f[1])); err != nil {
			return err
		}
	}
	return nil
}

// writeNew writes a file that must not exist yet: it never opens an existing path.
func writeNew(path string, data []byte) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

// genInstance is the environment's usable Instance of g (nil before its first use).
func genInstance(ix *Index, g *genMod) *store.Mod {
	for _, m := range ix.Mods {
		if genOf(m) == g && m.Status == identity.Live && !m.Residue && m.Unloadable == "" {
			return m
		}
	}
	return nil
}

// ensureGenMod makes a generated Mod exist and known: the looks directory, the Mod's
// folder with its About.xml, the shared source src:looks, and a scan of that source alone
// when it has no Instance yet (as Archo Monitor's folder is read, 19 §6).
func (a *App) ensureGenMod(g *genMod, gameRoot string) (m *store.Mod, dir string, chosen bool, err error) {
	if dir, chosen, err = a.ensureLooksDir(gameRoot); err != nil {
		return nil, "", false, err
	}
	if err := g.skeleton(g.dir(dir)); err != nil {
		return nil, dir, chosen, err
	}
	src, err := a.sharedSource(LooksLabel, dir)
	if err != nil {
		return nil, dir, chosen, err
	}
	ix, err := a.Index()
	if err != nil {
		return nil, dir, chosen, err
	}
	if m = genInstance(ix, g); m == nil {
		if _, err := a.ScanWith(ScanOptions{Sources: []string{src.ID}}); err != nil {
			return nil, dir, chosen, err
		}
		if ix, err = a.Index(); err != nil {
			return nil, dir, chosen, err
		}
		if m = genInstance(ix, g); m == nil {
			return nil, dir, chosen, fmt.Errorf("the scan did not find %s in %s", g.Name, dir)
		}
	}
	return m, dir, chosen, nil
}

// takeGenerated takes the generated Mods' entries out of l: a sort orders the rest and puts
// them back at the end, in the order of generated.
func takeGenerated(st *LoadoutState, l loadout.List) (rest, entries loadout.List) {
	found := map[*genMod]loadout.Entry{}
	rest = make(loadout.List, 0, len(l))
	for _, e := range l {
		if g := genOf(st.Ix.ByID[e.Instance]); g != nil {
			if _, dup := found[g]; !dup {
				found[g] = e
			}
			continue
		}
		rest = append(rest, e)
	}
	if len(found) == 0 {
		return l, nil
	}
	for _, g := range generated {
		if e, ok := found[g]; ok {
			entries = append(entries, e)
		}
	}
	return rest, entries
}

// genLast puts g at the end of the current plan as one undoable edit, with the other
// generated Mod the plan already has, in the order of generated; added reports a change.
func (a *App) genLast(g *genMod) (added bool, err error) {
	r, err := a.edit(g.addOp, func(st *LoadoutState, l loadout.List) (loadout.List, []string, error) {
		m := genInstance(st.Ix, g)
		if m == nil {
			return nil, nil, errors.New(g.Name + " is not installed")
		}
		rest, entries := takeGenerated(st, l)
		out := rest.Clone()
		for _, o := range generated {
			if o == g {
				out = append(out, loadout.Entry{Instance: m.ID})
				continue
			}
			for _, e := range entries {
				if genOf(st.Ix.ByID[e.Instance]) == o {
					out = append(out, e)
				}
			}
		}
		return out, nil, nil
	})
	if err != nil {
		return false, err
	}
	return len(r.Changes) > 0, nil
}

// LooksFile is one file of a generated Mod.
type LooksFile struct {
	Rel    string // relative to the generated Mod's folder, forward slashes
	Source string // the Mod's file
	Size   int64
	MTime  int64  // the source's, unix nanoseconds
	Linked bool   // a hard link (in a dry run: expected to be one); false: a copy
	Look   string // the look and slot it is written for
	Slot   string
}

// GenText is one text file RimArcho writes into a generated Mod (Defs, patches).
type GenText struct {
	Rel  string // relative to the generated Mod's folder, forward slashes
	Data string
}

// LooksBuild is one rebuild of a generated Mod, or with DryRun what it would write.
type LooksBuild struct {
	Dir       string // the generated Mod's folder
	Files     []LooksFile
	Texts     []GenText // RimArcho Styles Preference: its Defs and patches
	DryRun    bool
	Unchanged bool // the result equals what is on disk: nothing was written
	Links     int
	Copies    int
}

// genCurrent reports whether the generated Mod in dir already holds exactly files and
// texts: the recorded set (rel, source, size, mtime) equals files and every file is there,
// and each text file has the planned content (one that is not planned is absent).
func (a *App) genCurrent(g *genMod, dir string, files []LooksFile, texts []GenText) (bool, error) {
	rec, err := g.files(a.Store)
	if err != nil {
		return false, err
	}
	if _, err := os.Lstat(dir); err != nil {
		return len(files) == 0 && len(texts) == 0 && len(rec) == 0, nil // nothing was ever built and nothing is due
	}
	if _, err := os.Lstat(filepath.Join(dir, "About", "About.xml")); err != nil || len(rec) != len(files) {
		return false, nil
	}
	if _, err := os.Lstat(filepath.Join(dir, filepath.FromSlash(genStub))); err != nil {
		return false, nil // built before generated Mods carried the file
	}
	for i, f := range files { // both are ordered by Rel
		r := rec[i]
		if r.Rel != f.Rel || r.Source != f.Source || r.Size != f.Size || r.MTime != f.MTime {
			return false, nil
		}
		if _, err := os.Lstat(filepath.Join(dir, filepath.FromSlash(f.Rel))); err != nil {
			return false, nil
		}
	}
	want := map[string]string{}
	for _, t := range texts {
		want[t.Rel] = t.Data
	}
	for _, rel := range g.texts {
		data, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
		if planned, ok := want[rel]; ok != (err == nil) || (ok && !bytes.Equal(data, []byte(planned))) {
			return false, nil
		}
	}
	for i := range files {
		files[i].Linked = rec[i].Linked
	}
	return true, nil
}

var errLooksRefused = errors.New("looks: rebuild refused")

// genRebuild rebuilds the generated Mod g in the looks directory dir for st's plan (21 §4
// "Rebuild"). A result equal to what is on disk writes nothing; otherwise it is refused
// while a game runs, built in a folder beside the Mod's and swapped in. dryRun writes
// nothing and still reports the refusal. h is the parent operation-log row, if any.
func (a *App) genRebuild(g *genMod, st *LoadoutState, dir string, files []LooksFile, texts []GenText, dryRun bool, h *oplog.Handle) (*LooksBuild, error) {
	b := &LooksBuild{Dir: g.dir(dir), DryRun: dryRun, Files: files, Texts: texts}
	same, err := a.genCurrent(g, b.Dir, b.Files, b.Texts)
	if err != nil {
		return b, err
	}
	if b.Unchanged = same; !same {
		a.looksExpectLinks(b)
		err = a.genRefusal(g, dir)
		if err == nil && !dryRun {
			err = a.genWrite(g, b)
		}
	}
	for _, f := range b.Files {
		if f.Linked {
			b.Links++
		} else {
			b.Copies++
		}
	}
	if !dryRun && !same {
		row := oplog.Row{Op: g.buildOp, EnvID: st.Ix.Env.ID, Subject: st.Plan.Name, Target: b.Dir,
			Result: opResult(err, errors.Is(err, errLooksRefused)), Detail: errText(err)}
		if err == nil {
			row.Detail = fmt.Sprintf("%s (%s, %s)", plural(len(b.Files), "file"), plural(b.Links, "hard link"), plural(b.Copies, "copy"))
			if len(b.Texts) > 0 {
				row.Detail += ", " + plural(len(b.Texts), "Def file")
			}
		}
		a.opAdd(h, row)
	}
	return b, err
}

// genRefusal says why the generated Mod cannot be replaced now: a game runs (09 §4), or
// the looks directory overlaps the data directory or a source root.
func (a *App) genRefusal(g *genMod, dir string) error {
	if run, err := a.RunningGame(); err != nil {
		return err
	} else if run != nil {
		return fmt.Errorf("%w: %s is not rebuilt while a game runs (%s); the %s are kept and the next write to the game rebuilds it", errLooksRefused, g.Name, run.Describe(a.Loc), g.kept)
	}
	if err := a.looksDirReady(dir); err != nil {
		return fmt.Errorf("%w: %v", errLooksRefused, err)
	}
	return nil
}

// looksExpectLinks marks the files a rebuild expects to hard-link: the source is on the
// Mod's volume and is not read-only (deleting a link to a read-only file clears the
// attribute, which the Mod's file shares).
func (a *App) looksExpectLinks(b *LooksBuild) {
	same := a.SameVolume
	if same == nil {
		same = source.SameVolume
	}
	for i := range b.Files {
		f := &b.Files[i]
		fi, err := os.Stat(f.Source)
		f.Linked = err == nil && fi.Mode().Perm()&0o200 != 0 && same(f.Source, b.Dir)
	}
}

// genWrite builds b in a folder beside the generated Mod's and swaps it in, then records
// the files. Every destination is a new path in a new folder.
func (a *App) genWrite(g *genMod, b *LooksBuild) error {
	tmp := b.Dir + TmpSuffix
	if err := os.RemoveAll(tmp); err != nil {
		return err
	}
	fail := func(err error) error {
		os.RemoveAll(tmp)
		return err
	}
	if err := g.skeleton(tmp); err != nil {
		return fail(err)
	}
	for _, t := range b.Texts {
		dst := filepath.Join(tmp, filepath.FromSlash(t.Rel))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return fail(err)
		}
		if err := writeNew(dst, []byte(t.Data)); err != nil {
			return fail(err)
		}
	}
	link := a.HardLink
	if link == nil {
		link = os.Link
	}
	rec := make([]store.LookFile, 0, len(b.Files))
	for i := range b.Files {
		f := &b.Files[i]
		dst := filepath.Join(tmp, filepath.FromSlash(f.Rel))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return fail(err)
		}
		if !f.Linked || link(f.Source, dst) != nil {
			f.Linked = false
			if err := copyNew(f.Source, dst); err != nil {
				return fail(fmt.Errorf("copying %s: %w", f.Source, err))
			}
		}
		rec = append(rec, store.LookFile{Rel: f.Rel, Source: f.Source, Size: f.Size, MTime: f.MTime, Linked: f.Linked})
	}
	if err := swapDir(tmp, b.Dir); err != nil {
		return fail(err)
	}
	return g.replace(a.Store, rec)
}

// copyNew copies src to dst, which must not exist: it never opens an existing destination.
func copyNew(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

// swapDir puts the folder tmp in dir's place; the folder that was there is deleted (links
// and copies only: deleting a hard link leaves the Mod's file).
func swapDir(tmp, dir string) error {
	old := dir + genOldSuffix
	if err := os.RemoveAll(old); err != nil {
		return err
	}
	if _, err := os.Lstat(dir); err != nil {
		return os.Rename(tmp, dir)
	}
	if err := os.Rename(dir, old); err != nil {
		return err
	}
	if err := os.Rename(tmp, dir); err != nil {
		os.Rename(old, dir)
		return err
	}
	os.RemoveAll(old)
	return nil
}

// generatedForWrite rebuilds the generated Mods the plan has for the plan being written to
// the game (21 §4, §5; 07 §4), in one pass over one index, so a Mod update that replaced a
// linked file is picked up. A Mod whose rebuild fails is marked to be left out of this
// write, alone; the reason comes back per Mod.
func (a *App) generatedForWrite(st *LoadoutState, dryRun bool) (looksErr, stylesErr string) {
	entry := map[*genMod]*store.Mod{}
	for _, e := range st.List {
		if m := st.Ix.ByID[e.Instance]; IsGenerated(m) && m.Status == identity.Live {
			entry[genOf(m)] = m
		}
	}
	if len(entry) == 0 {
		return "", ""
	}
	var h *oplog.Handle
	if st.op != nil {
		h = st.op.h
	}
	ls, lsErr := a.LooksState(context.Background(), st, nil)
	fail := func(m *store.Mod, err error) string {
		if st.leaveOut == nil {
			st.leaveOut = map[string]bool{}
		}
		st.leaveOut[m.ID] = true
		return strings.TrimPrefix(err.Error(), errLooksRefused.Error()+": ")
	}
	if m := entry[looksGen]; m != nil {
		err := lsErr
		if err == nil {
			_, err = a.looksRebuild(ls, filepath.Dir(modDir(st.Ix, m)), dryRun, h)
		}
		if err != nil {
			looksErr = fail(m, err)
		}
	}
	if m := entry[stylesGen]; m != nil {
		err := lsErr
		if err == nil {
			_, err = a.stylesRebuild(ls, filepath.Dir(modDir(st.Ix, m)), dryRun, h)
		}
		if err != nil {
			stylesErr = fail(m, err)
		}
	}
	return looksErr, stylesErr
}
