// What RimArcho Styles Preference holds (21 §5): Textures/RimArchoStyles/… (links or copies
// of Mods' files under paths no other Mod uses), Defs/RimArchoStyles.xml (one ThingStyleDef
// per style entry and thing Def) and Patches/RimArchoStyles.xml (the attachments). Every
// XML shape below was checked against the game's own files (RimWorld 1.6.4871, Data/):
//
//   - ThingStyleDef with graphicData and wornGraphicPath:
//     Ideology/Defs/ThingStyleDefs/ThingStyleDefs.xml (Hindu_SimpleHelmet; a style repeats
//     drawSize and the like, Morbid_IdeogramA, so the thing Def's graphicData is copied).
//   - StyleCategoryDef/thingDefStyles/li with thingDef and styleDef:
//     Ideology/Defs/StyleCategoryDefs/StyleCategoryDefs.xml.
//   - ThingDef/randomStyleChance and randomStyle/li/styleDef:
//     Anomaly/Defs/ThingDefs_Misc/Apparel_Cult.xml, Royalty/Defs/ThingDefs_Misc/Apparel_Various.xml
//     (0.5 with one style; Royalty alone, so not tied to Ideology).
//   - Graphic_Random over a folder: Core/Defs/ThingDefs_Buildings/Buildings_Ancient.xml and
//     the Christian_SculptureSmall style.
//   - <Patch><Operation Class="PatchOperationAdd|PatchOperationReplace"> with xpath and
//     value: Royalty/Patches/Recipes_Prosthetics.xml, Ideology/Patches/Traits.xml.
//
// PatchOperationConditional (xpath, match, nomatch) is the game's class too, but no official
// file uses it; it is how an attachment tests for its Def first, so that a category or thing
// Def that is absent is skipped without an error. MayRequire is not used: the official
// files put it on Defs and list items only, never on a patch operation, and it names a Mod
// where the test here is for the Def itself.

const (
	stylesDefsRel  = "Defs/RimArchoStyles.xml"
	stylesPatchRel = "Patches/RimArchoStyles.xml"
	// stylesTexRoot is the folder under Textures/ that only this Mod uses: a Graphic_Random
	// over a folder takes every Mod's files at that path.
	stylesTexRoot = "RimArchoStyles"
	// styleRandomChance is the randomStyleChance a thing Def gets when it has none.
	styleRandomChance = "0.5"
	stylesHeader      = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by RimArcho (looks). Rebuilt before every write to the game; do not edit. -->\n"
)

func xmlText(s string) string {
	return strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
}

// commentText makes s safe inside an XML comment.
func commentText(s string) string { return strings.ReplaceAll(s, "--", "- -") }

// defNamePart keeps the characters a defName may have.
func defNamePart(s string) string {
	return strings.Map(func(r rune) rune {
		if r == '_' || r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' {
			return r
		}
		return '_'
	}, s)
}

// StyleDefName is the defName of the ThingStyleDef a style entry generates for a thing Def.
// It carries the entry's ID, which is never reused, so a save's reference stays right.
func StyleDefName(entry int64, thing string) string {
	return fmt.Sprintf("RimArchoStyle_%d_%s", entry, defNamePart(thing))
}

// patchOp is one patch operation; match and nomatch are a conditional's branches.
type patchOp struct {
	class, xpath   string
	value          []string // lines inside <value>
	match, nomatch *patchOp
}

func opAddXML(xpath string, value ...string) *patchOp {
	return &patchOp{class: "PatchOperationAdd", xpath: xpath, value: value}
}

func opReplace(xpath string, value ...string) *patchOp {
	return &patchOp{class: "PatchOperationReplace", xpath: xpath, value: value}
}

func opIf(xpath string, match, nomatch *patchOp) *patchOp {
	return &patchOp{class: "PatchOperationConditional", xpath: xpath, match: match, nomatch: nomatch}
}

func (o *patchOp) write(sb *strings.Builder, tag, indent string) {
	fmt.Fprintf(sb, "%s<%s Class=\"%s\">\n%s  <xpath>%s</xpath>\n", indent, tag, o.class, indent, xmlText(o.xpath))
	if len(o.value) > 0 {
		sb.WriteString(indent + "  <value>\n")
		for _, line := range o.value {
			sb.WriteString(indent + "    " + line + "\n")
		}
		sb.WriteString(indent + "  </value>\n")
	}
	if o.match != nil {
		o.match.write(sb, "match", indent+"  ")
	}
	if o.nomatch != nil {
		o.nomatch.write(sb, "nomatch", indent+"  ")
	}
	fmt.Fprintf(sb, "%s</%s>\n", indent, tag)
}

func defPath(typ, name string) string { return fmt.Sprintf(`Defs/%s[defName="%s"]`, typ, name) }

// attachStyle adds the row (thing, style) to a style category's thingDefStyles, when the
// thing Def and the category are loaded; a category without the list gets one.
func attachStyle(category, thing, style string) *patchOp {
	cat := defPath("StyleCategoryDef", category)
	row := []string{"<li>", "  <thingDef>" + xmlText(thing) + "</thingDef>", "  <styleDef>" + style + "</styleDef>", "</li>"}
	list := append(append([]string{"<thingDefStyles>"}, indentLines(row)...), "</thingDefStyles>")
	return opIf(defPath("ThingDef", thing),
		opIf(cat+"/thingDefStyles", opAddXML(cat+"/thingDefStyles", row...), opIf(cat, opAddXML(cat, list...), nil)), nil)
}

// randomStyle adds the style to a thing Def's randomStyle, and gives the Def a
// randomStyleChance when it writes none.
func randomStyle(thing, style string) []*patchOp {
	def := defPath("ThingDef", thing)
	row := []string{"<li>", "  <styleDef>" + style + "</styleDef>", "</li>"}
	list := append(append([]string{"<randomStyle>"}, indentLines(row)...), "</randomStyle>")
	return []*patchOp{
		opIf(def+"/randomStyle", opAddXML(def+"/randomStyle", row...), opIf(def, opAddXML(def, list...), nil)),
		opIf(def+"/randomStyleChance", nil, opIf(def, opAddXML(def, "<randomStyleChance>"+styleRandomChance+"</randomStyleChance>"), nil)),
	}
}

// setGraphic sets one field of a Def's graphicData, whether the Def writes the field, only
// graphicData, or inherits both; a Def that is not loaded is left alone.
func setGraphic(def, field, value string) *patchOp {
	line := "<" + field + ">" + xmlText(value) + "</" + field + ">"
	gd := def + "/graphicData"
	return opIf(gd+"/"+field, opReplace(gd+"/"+field, line),
		opIf(gd, opAddXML(gd, line), opIf(def, opAddXML(def, "<graphicData>", "  "+line, "</graphicData>"), nil)))
}

func indentLines(lines []string) []string {
	out := make([]string, len(lines))
	for i, l := range lines {
		out[i] = "  " + l
	}
	return out
}

// texSuffix is what follows the look's path in a file's content path: the facing, body
// type or mask suffix (or, in a folder look, "/" and the file name) with the extension.
func texSuffix(l *looks.Look, f *looks.File) (string, bool) {
	if len(f.Tex) < len(l.ID) || !strings.EqualFold(f.Tex[:len(l.ID)], l.ID) {
		return "", false
	}
	return f.Tex[len(l.ID):], true
}

// lookName is the last part of a look's path as the Mod writes it.
func lookName(l *looks.Look, p *looks.Provider) string {
	name := l.ID[strings.LastIndexByte(l.ID, '/')+1:]
	slots := make([]string, 0, len(p.Slots))
	for s := range p.Slots {
		slots = append(slots, s)
	}
	sort.Strings(slots)
	for _, s := range slots {
		if f := p.Slots[s]; len(f.Tex) >= len(l.ID) && strings.EqualFold(f.Tex[:len(l.ID)], l.ID) {
			return f.Tex[len(l.ID)-len(name) : len(l.ID)]
		}
	}
	return name
}

// slotBody is a worn slot's body type ("" for a slot without one).
func slotBody(slot string) string {
	slot = strings.TrimSuffix(slot, "_mask")
	if i := strings.LastIndexByte(slot, '_'); i > 0 {
		return slot[:i]
	}
	return ""
}

// stylesBuilder collects the generated Mod's files, Defs and patches.
type stylesBuilder struct {
	ls      *LooksState
	files   []LooksFile
	seen    map[string]bool
	defs    strings.Builder
	patches strings.Builder
}

// put adds f, and its second format, under base with the suffix it has in the look l.
func (b *stylesBuilder) put(base string, l *looks.Look, f *looks.File, slot string) {
	for ; f != nil; f = f.Alt {
		suffix, ok := texSuffix(l, f)
		rel := "Textures/" + base + suffix
		if !ok || b.seen[strings.ToLower(rel)] {
			continue
		}
		b.seen[strings.ToLower(rel)] = true
		b.files = append(b.files, LooksFile{Rel: rel, Source: f.Path, Size: f.Size, MTime: f.MTime, Look: l.ID, Slot: slot})
	}
}

func (b *stylesBuilder) op(o *patchOp) { o.write(&b.patches, "Operation", "  ") }

// style writes one style entry: the Mod's textures of the look under a path of the entry's
// own, a ThingStyleDef per thing Def, and the attachments.
func (b *stylesBuilder) style(e *StyleEntryState, l *looks.Look) {
	p := lookProviderAt(l, e.Pos)
	own := fmt.Sprintf("%s/Style/%d/%s", stylesTexRoot, e.ID, lookName(l, p))
	bodies := map[string]bool{}
	ground := false
	for slot, f := range p.Slots {
		b.put(own, l, f, slot)
		bodies[slotBody(slot)] = true
		ground = ground || slotBody(slot) == ""
	}
	if l.Kind == looks.KindWorn {
		// A body type the Mod does not draw keeps what the game shows now, so that no
		// pawn wears a missing texture.
		for slot, w := range l.InGame(b.ls.ChoiceOf(l.ID)) {
			if body := slotBody(slot); body != "" && !bodies[body] {
				b.put(own, l, w.File, slot)
			}
		}
	}
	fmt.Fprintf(&b.defs, "  <!-- entry %d: %s, style in %s -->\n", e.ID, commentText(l.ID), commentText(e.Target))
	fmt.Fprintf(&b.patches, "  <!-- entry %d: %s, style in %s -->\n", e.ID, commentText(l.ID), commentText(e.Target))
	for _, th := range styleThings(b.ls.Index, l) {
		if !contains(e.Things, th.name) {
			continue
		}
		name := StyleDefName(e.ID, th.name)
		tex, worn := th.t.TexPath, th.t.WornPath
		if th.ground && (l.Kind != looks.KindWorn || ground) {
			tex = own
		}
		if th.worn {
			worn = own
		}
		b.styleDef(name, tex, worn, th.t)
		b.op(attachStyle(e.Target, th.name, name))
		if e.Random {
			for _, o := range randomStyle(th.name, name) {
				b.op(o)
			}
		}
	}
}

// styleDef writes a ThingStyleDef: the thing Def's graphicData with another texPath.
func (b *stylesBuilder) styleDef(name, tex, worn string, t *looks.Thing) {
	d := &b.defs
	d.WriteString("  <ThingStyleDef>\n    <defName>" + name + "</defName>\n")
	if worn != "" {
		d.WriteString("    <wornGraphicPath>" + xmlText(worn) + "</wornGraphicPath>\n")
	}
	if tex != "" && t.GraphicClass != "" {
		d.WriteString("    <graphicData>\n      <texPath>" + xmlText(tex) + "</texPath>\n      <graphicClass>" + xmlText(t.GraphicClass) + "</graphicClass>\n")
		if t.Graphic != "" {
			d.WriteString("      " + t.Graphic + "\n")
		}
		d.WriteString("    </graphicData>\n")
	}
	d.WriteString("  </ThingStyleDef>\n")
}

// variantSet is one target with the entries that add a variant to it.
type variantSet struct {
	vt      variantTarget
	entries []*StyleEntryState
}

// variants writes one target's folder: what the game shows there now (v0) and each
// entry's Mod's version (v1, v2, … in the order the entries were added), and the patch
// that makes the target a Graphic_Random over it. Only the textures the class draws are
// placed: every other file in the folder would be a variant of its own.
func (b *stylesBuilder) variants(set *variantSet) {
	vt := set.vt
	folder := fmt.Sprintf("%s/Random/%s", stylesTexRoot, styleKey(vt.defType, vt.defName))
	keep := func(slot string) bool {
		slot = strings.TrimSuffix(slot, "_mask")
		if styleClass(vt.class) == "Graphic_Single" {
			return slot == "single"
		}
		return slot == "south" || slot == "east" || slot == "north" || slot == "west"
	}
	for slot, w := range vt.look.InGame(b.ls.ChoiceOf(vt.look.ID)) {
		if keep(slot) {
			b.put(folder+"/v0", vt.look, w.File, slot)
		}
	}
	for n, e := range set.entries {
		l := b.ls.Index.ByID[e.Look]
		for slot, f := range lookProviderAt(l, e.Pos).Slots {
			if keep(slot) {
				b.put(fmt.Sprintf("%s/v%d", folder, n+1), l, f, slot)
			}
		}
	}
	fmt.Fprintf(&b.patches, "  <!-- random variants of %s %s -->\n", vt.defType, commentText(vt.defName))
	def := defPath(vt.defType, vt.defName)
	b.op(setGraphic(def, "texPath", folder))
	b.op(setGraphic(def, "graphicClass", "Graphic_Random"))
}

// stylesPlan lists the files and writes the Defs and patches of the generated Mod for the
// active entries of ss.
func stylesPlan(ss *StylesState) ([]LooksFile, []GenText) {
	b := &stylesBuilder{ls: ss.Ls, seen: map[string]bool{}}
	idx := ss.Ls.Index
	var sets []*variantSet
	setOf := map[string]*variantSet{}
	for i := range ss.Entries {
		e := &ss.Entries[i]
		l := idx.ByID[e.Look]
		if e.State != StyleActive || l == nil {
			continue
		}
		if e.Kind == StyleKindStyle {
			b.style(e, l)
			continue
		}
		for _, vt := range variantTargets(idx, l, e.Target) {
			if !contains(e.Things, vt.defName) {
				continue
			}
			key := vt.defType + "|" + vt.defName
			if setOf[key] == nil {
				setOf[key] = &variantSet{vt: vt}
				sets = append(sets, setOf[key])
			}
			setOf[key].entries = append(setOf[key].entries, e)
		}
	}
	for _, set := range sets {
		b.variants(set)
	}
	sort.Slice(b.files, func(i, j int) bool { return b.files[i].Rel < b.files[j].Rel })
	var texts []GenText
	if b.defs.Len() > 0 {
		texts = append(texts, GenText{Rel: stylesDefsRel, Data: stylesHeader + "<Defs>\n" + b.defs.String() + "</Defs>\n"})
	}
	if b.patches.Len() > 0 {
		texts = append(texts, GenText{Rel: stylesPatchRel, Data: stylesHeader + "<Patch>\n" + b.patches.String() + "</Patch>\n"})
	}
	return b.files, texts
}
