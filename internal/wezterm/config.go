// Package wezterm generates the configuration RimArcho hands to its WezTerm host (06 §1.2).
// The settings were validated in V0 (07 §6.2); the download and launch flow is V5.
package wezterm

import (
	"strings"
)

// Config returns the wezterm.lua for a bundled-font directory.
func Config(fontDir string) string {
	return strings.Replace(template, "{{FONT_DIR}}", luaString(fontDir), 1)
}

// luaString quotes s as a Lua long string whose level is longer than any "]=…=]" in s.
func luaString(s string) string {
	eq := ""
	for strings.Contains(s, "]"+eq+"]") {
		eq += "="
	}
	return "[" + eq + "[" + s + "]" + eq + "]"
}

const template = `-- Generated by RimArcho (06 §1.2). It is rewritten on every start; edits are lost.
local wezterm = require 'wezterm'
local config = wezterm.config_builder()

-- The bundled Maple Mono NF CN has the Nerd Font icons and CJK glyphs. Fallbacks cover the
-- compatibility glyphs Maple lacks; restricting font_locator to these dirs would turn them
-- into boxes (V0).
config.font_dirs = { {{FONT_DIR}} }
config.font = wezterm.font_with_fallback({ 'Maple Mono NF CN', 'Symbols Nerd Font Mono', 'Cascadia Mono', 'Segoe UI Symbol' })
config.font_size = 11.0
config.harfbuzz_features = { 'calt=0', 'clig=0', 'liga=0' }

-- Widths must match RimArcho's (East Asian ambiguous = 1 cell).
config.treat_east_asian_ambiguous_width_as_wide = false
config.unicode_version = 14

config.colors = {
  foreground = '#E6E6E6', background = '#0E0F12',
  cursor_bg = '#A5B4FC', cursor_fg = '#0E0F12', cursor_border = '#A5B4FC',
  selection_bg = '#2C2E4A', selection_fg = '#E6E6E6',
}
config.enable_tab_bar = false
config.enable_scroll_bar = false
config.window_padding = { left = 8, right = 8, top = 6, bottom = 6 }
config.initial_cols = 160
config.initial_rows = 46
wezterm.on('format-window-title', function() return 'RimArcho' end)

-- Close when archo exits cleanly; keep the window when it fails, so the error stays readable.
config.exit_behavior = 'CloseOnCleanExit'
config.window_close_confirmation = 'NeverPrompt'
config.audible_bell = 'Disabled'
config.check_for_updates = false
config.show_update_window = false
config.automatically_reload_config = false
config.enable_kitty_graphics = false -- iTerm2 inline images are always on
return config
`
