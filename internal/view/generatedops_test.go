package view_test

import (
	"context"
	"slices"
	"testing"

	"github.com/ToumanLin/RimArcho/internal/app"
	"github.com/ToumanLin/RimArcho/internal/view"
)

// 16 §2.9 "Generated Mods": a generated Mod's row offers none of the actions the app
// refuses for it (lock, update, move, separate, recycle, textures); a tag, a note and
// "open the folder" stay, and so do the plan's own ops. Its source has its own name.
func TestGeneratedModOffersNoFolderOps(t *testing.T) {
	e := looksHome(t)
	if _, err := e.App.LooksApply(context.Background(), looksGun, "pkg:looks.a", nil, app.LooksPlan, false); err != nil {
		t.Fatal(err)
	}
	lib, err := e.App.Library()
	if err != nil {
		t.Fatal(err)
	}
	var gl *app.LibLineage
	var gi, plain *app.LibInstance
	for _, l := range lib.Lineages {
		for _, i := range l.Instances {
			switch {
			case app.IsGenerated(i.Mod):
				gl, gi = l, i
			case i.Mod != nil && i.Mod.PackageID == "looks.c":
				plain = i
			}
		}
	}
	if gi == nil || plain == nil {
		t.Fatal("fixture: the library lacks the generated Mod or Charlie")
	}
	refused := []string{view.OpPin, view.OpPinUpdate, view.OpUnpin, view.OpMove, view.OpSeparate, view.OpDelete, view.OpTextures, view.OpUnsub, view.OpResub, view.OpSubRemove}
	for _, page := range []string{view.LibraryPage, view.EditorPage} {
		ops := view.CopyOps(lib, gl, gi, page)
		for _, k := range refused {
			if slices.Contains(ops, k) {
				t.Errorf("%s: the generated Mod offers %s (%v)", page, k, ops)
			}
		}
		for _, k := range []string{view.OpFolder, view.OpTags, view.OpNote} {
			if !slices.Contains(ops, k) {
				t.Errorf("%s: the generated Mod lacks %s (%v)", page, k, ops)
			}
		}
	}
	if ops := view.CopyOps(lib, gl, gi, view.EditorPage); !slices.Contains(ops, view.OpDisable) {
		t.Errorf("the plan decides whether it is enabled: %v", ops)
	}
	// the fixture's own Mod in Mods/ still has them: the gate is IsGenerated, not the folder kind
	if ops := view.CopyOps(lib, nil, plain, view.LibraryPage); !slices.Contains(ops, view.OpPin) || !slices.Contains(ops, view.OpDelete) {
		t.Fatalf("a Mod of the player's lost its ops: %v", ops)
	}
	if gi.Source != app.LibLooks || view.LibSourceText(gi.Source) != "looks" {
		t.Fatalf("source %q shown as %q", gi.Source, view.LibSourceText(gi.Source))
	}
	if got := view.CopyNoteAuto(gi); got != "generated by RimArcho from the looks choices" {
		t.Fatalf("copy note %q", got)
	}
}
