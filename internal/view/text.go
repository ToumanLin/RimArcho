// Package view holds what the TUI and the GUI show, independent of how they draw it
// (08 §1): view models built from internal/app, and the interface text.
//
// The interfaces speak Chinese or English (06 §1, "跟随配置"); command output shown in panels
// is the fixed-English CLI text (05 §1). Strings are looked up by their English text.

var lang = "en"

// Lang is the selected language: "zh" or "en".
func Lang() string { return lang }

// Register adds a surface's own translations (its key hints, its help text).
func Register(zh map[string]string) {
	for k, v := range zh {
		zhText[k] = v
	}
}

// Table is the whole translation table of the selected language (empty for English); the
// GUI fetches it once.
func Table() map[string]string {
	if lang != "zh" {
		return map[string]string{}
	}
	return zhText
}

// SetLang selects the interface language: "zh", "en" or "auto" (ARCHO_LANG, then the OS UI
// language).
func SetLang(v string) {
	if e := os.Getenv("ARCHO_LANG"); e != "" {
		v = e
	}
	if v == "" || v == "auto" {
		v = systemLang()
	}
	if strings.HasPrefix(strings.ToLower(v), "zh") {
		lang = "zh"
	} else {
		lang = "en"
	}
}

// T translates an interface string.
func T(s string) string {
	if lang == "zh" {
		if z, ok := zhText[s]; ok {
			return z
		}
	}
	return s
}

// Tf translates a format string, then formats.
func Tf(f string, a ...any) string { return fmt.Sprintf(T(f), a...) }

